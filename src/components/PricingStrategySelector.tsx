import React, { useState, useEffect } from 'react';
import { ComparableStats } from '../services/dataService';
import { Sparkles, Shield, DollarSign, Award, ArrowUpRight, RefreshCw } from 'lucide-react';

interface PricingStrategySelectorProps {
  stats: ComparableStats;
}

export type StrategyTier = 'budget' | 'market' | 'premium';

export const PricingStrategySelector: React.FC<PricingStrategySelectorProps> = ({ stats }) => {
  const [selectedStrategy, setSelectedStrategy] = useState<StrategyTier>('market');
  const [explanations, setExplanations] = useState<{
    budget: string;
    market: string;
    premium: string;
  }>({
    budget: `Budget pricing ($${stats.p25.toFixed(2)}/night, 25th percentile): 25% of the ${stats.count} comparable listings in ${stats.neighbourhood} charge $${stats.p25.toFixed(2)} or less.`,
    market: `Market pricing ($${stats.median.toFixed(2)}/night, median): the statistical midpoint of the ${stats.count} comparable listings in ${stats.neighbourhood}.`,
    premium: `Premium pricing ($${stats.p75.toFixed(2)}/night, 75th percentile): 25% of the ${stats.count} comparable listings in ${stats.neighbourhood} charge $${stats.p75.toFixed(2)} or more.`,
  });
  const [loading, setLoading] = useState(false);

  // Fetch explanation from Gemini API via /api/strategy-explanation
  useEffect(() => {
    let isCancelled = false;

    async function fetchExplanation() {
      setLoading(true);
      try {
        const response = await fetch('/api/strategy-explanation', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            neighbourhood: stats.neighbourhood,
            bedrooms: stats.bedrooms,
            minNightsCap: stats.minNightsCap,
            count: stats.count,
            p25: stats.p25,
            median: stats.median,
            p75: stats.p75,
            licensedCount: stats.licensedCount,
            licensedMedianPrice: stats.licensedMedianPrice,
            licensedMedianRevenue: stats.licensedMedianRevenue,
            unlicensedCount: stats.unlicensedCount,
            unlicensedMedianPrice: stats.unlicensedMedianPrice,
            unlicensedMedianRevenue: stats.unlicensedMedianRevenue,
            commonPropertyTypes: stats.commonPropertyTypes,
          }),
        });

        if (response.ok && !isCancelled) {
          const data = await response.json();
          if (data.budget && data.market && data.premium) {
            setExplanations({
              budget: data.budget,
              market: data.market,
              premium: data.premium,
            });
          }
        }
      } catch (err) {
        console.warn('Using local fallback explanations for strategies:', err);
      } finally {
        if (!isCancelled) setLoading(false);
      }
    }

    fetchExplanation();

    return () => {
      isCancelled = true;
    };
  }, [stats.neighbourhood, stats.bedrooms, stats.minNightsCap, stats.count, stats.median]);

  const strategies: {
    key: StrategyTier;
    name: string;
    price: number;
    percentileLabel: string;
    badge: string;
    description: string;
    icon: React.ReactNode;
  }[] = [
    {
      key: 'budget',
      name: 'Budget Strategy',
      price: stats.p25,
      percentileLabel: '25th Percentile',
      badge: '25th Percentile',
      description: `25% of the ${stats.count} comparable listings charge $${stats.p25.toFixed(2)} or less.`,
      icon: <DollarSign className="w-4 h-4 text-blue-600" />,
    },
    {
      key: 'market',
      name: 'Market Strategy (Recommended)',
      price: stats.median,
      percentileLabel: '50th Percentile (Median)',
      badge: 'Market Median',
      description: `Median of the ${stats.count} comparable listings.`,
      icon: <Award className="w-4 h-4 text-amber-600" />,
    },
    {
      key: 'premium',
      name: 'Premium Strategy',
      price: stats.p75,
      percentileLabel: '75th Percentile',
      badge: '75th Percentile',
      description: `25% of the ${stats.count} comparable listings charge $${stats.p75.toFixed(2)} or more.`,
      icon: <ArrowUpRight className="w-4 h-4 text-purple-600" />,
    },
  ];

  return (
    <div className="bg-white/[0.04] rounded-2xl border border-white/10 shadow-xl shadow-black/40 p-6 backdrop-blur-md">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-5">
        <div>
          <div className="flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-violet-400" />
            <h3 className="text-lg font-semibold text-zinc-100 tracking-tight">
              Pricing Strategy Selector &amp; Advisory
            </h3>
          </div>
          <p className="text-xs text-zinc-400 mt-1">
            Compare tactical listing tiers. Advisory rationale is generated by Gemini strictly using the computed statistics.
          </p>
        </div>

        <div className="flex items-center gap-1.5 text-xs text-zinc-400 bg-white/[0.03] px-3 py-1.5 rounded-lg border border-white/10 shrink-0">
          <Shield className="w-3.5 h-3.5 text-emerald-400" />
          <span>Grounded in computed data</span>
        </div>
      </div>

      {/* 3 Strategy Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4 mb-5">
        {strategies.map((strat) => {
          const isSelected = selectedStrategy === strat.key;
          return (
            <div
              key={strat.key}
              onClick={() => setSelectedStrategy(strat.key)}
              className={`p-5 rounded-xl border transition-all duration-150 cursor-pointer relative ${
                isSelected
                  ? 'border-violet-500 bg-gradient-to-br from-violet-900/40 via-violet-950/50 to-indigo-950/40 text-zinc-100 shadow-lg shadow-violet-950/50 ring-1 ring-violet-500/50'
                  : 'border-white/10 bg-white/[0.03] hover:bg-white/[0.06] hover:border-white/20 text-zinc-300'
              }`}
            >
              <div className="flex items-center justify-between mb-3">
                <span
                  className={`text-2xs font-bold uppercase tracking-wider px-2 py-0.5 rounded-md ${
                    isSelected
                      ? 'bg-violet-500/30 text-violet-200 border border-violet-400/30'
                      : 'bg-white/[0.06] text-zinc-400 border border-white/5'
                  }`}
                >
                  {strat.badge}
                </span>
                <span className={`text-2xs ${isSelected ? 'text-violet-300' : 'text-zinc-500'}`}>
                  {strat.percentileLabel}
                </span>
              </div>

              <div className="text-sm font-semibold mb-1 text-zinc-100">{strat.name}</div>

              <div className="flex items-baseline gap-1 my-2">
                <span className="text-3xl font-bold tracking-tight text-zinc-100 tabular-numbers">
                  ${strat.price.toFixed(2)}
                </span>
                <span className={`text-xs ${isSelected ? 'text-violet-300' : 'text-zinc-400'}`}>
                  / night
                </span>
              </div>

              <div
                className={`text-xs pt-3 border-t mt-3 leading-relaxed ${
                  isSelected ? 'border-violet-500/30 text-zinc-300' : 'border-white/10 text-zinc-400'
                }`}
              >
                {strat.description}
              </div>
            </div>
          );
        })}
      </div>

      {/* Dynamic Gemini Advisory Explanation */}
      <div className="bg-black/30 border border-white/10 rounded-xl p-4.5 relative backdrop-blur-md">
        <div className="flex items-center justify-between mb-2">
          <div className="flex items-center gap-2">
            <span className="w-2 h-2 rounded-full bg-violet-400 animate-pulse" />
            <span className="text-xs font-bold uppercase tracking-wider text-zinc-300">
              Advisory Analysis:{' '}
              <span className="text-violet-300 capitalize font-semibold">
                {selectedStrategy} Rate (${(selectedStrategy === 'budget' ? stats.p25 : selectedStrategy === 'market' ? stats.median : stats.p75).toFixed(2)}/night)
              </span>
            </span>
          </div>

          {loading && (
            <span className="text-xs text-violet-300 flex items-center gap-1.5 font-mono">
              <RefreshCw className="w-3.5 h-3.5 animate-spin" />
              Synthesizing stats...
            </span>
          )}
        </div>

        <p className="text-sm text-zinc-200 leading-relaxed">
          {explanations[selectedStrategy]}
        </p>

        <div className="mt-3.5 pt-3 border-t border-white/10 flex flex-col sm:flex-row sm:items-center justify-between gap-1 text-xs text-zinc-400">
          <span>
            Target: <strong className="text-zinc-200">{selectedStrategy === 'budget' ? 'Budget (25th)' : selectedStrategy === 'market' ? 'Market (Median)' : 'Premium (75th)'}</strong> • Comps sample: {stats.count} listings
          </span>
          <span className="italic text-zinc-500 text-2xs">
            Gemini model strictly explains only code-passed numbers.
          </span>
        </div>
      </div>
    </div>
  );
};
